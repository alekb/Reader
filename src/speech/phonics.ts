/**
 * Phonics-aware speech helpers: say a pure sound, a letter name, a word, or
 * sound out a word grapheme by grapheme. Sounds use, in order of preference:
 *   1. a parent recording from IndexedDB,
 *   2. a bundled clip at /audio/sounds/<id>.mp3 (drop files in to use them),
 *   3. the TTS approximation in the GPC table.
 */
import { GPC_BY_ID, LETTER_NAMES } from '../content/gpcs'
import type { DecodableWord } from '../content/words'
import { enqueue, getVoiceGender, pause, playClip, setPhraseResolver, speak, speakNow, type VoiceGender } from './tts'
import { getRecordingUrl } from './recordings'

/**
 * Bundled audio generated by `npm run audio` (Google Cloud TTS, see
 * scripts/generate-audio.mjs): the female set in audio/, the male set in
 * audio/male/. Parent recordings always take precedence.
 */
interface AudioManifest {
  sounds: Record<string, string>
  letters: Record<string, string>
  words: Record<string, string>
  phrases: Record<string, string>
}
const EMPTY: AudioManifest = { sounds: {}, letters: {}, words: {}, phrases: {} }
const VOICE_DIR: Record<VoiceGender, string> = { female: 'audio/', male: 'audio/male/' }
const manifests: Partial<Record<VoiceGender, Promise<AudioManifest>>> = {}
function loadManifest(g: VoiceGender): Promise<AudioManifest> {
  const cached = manifests[g]
  if (cached) return cached
  const dir = `${import.meta.env.BASE_URL}${VOICE_DIR[g]}`
  const p: Promise<AudioManifest> = fetch(`${dir}manifest.json`)
    .then(async (r) => {
      // A voice set that was never generated comes back as 404 or as the app page: no clips.
      const m: Partial<AudioManifest> = r.ok ? await r.json().catch(() => EMPTY) : EMPTY
      // Store full URLs so a clip always plays from its own voice's folder.
      const out: AudioManifest = { sounds: {}, letters: {}, words: {}, phrases: {} }
      for (const k of ['sounds', 'letters', 'words', 'phrases'] as const) for (const [key, f] of Object.entries(m[k] ?? {})) out[k][key] = dir + f
      return out
    })
    .catch(() => {
      // Network failure: use the device voice for now and try again on the next clip.
      if (manifests[g] === p) delete manifests[g]
      return EMPTY
    })
  manifests[g] = p
  return p
}
/** A bundled clip in the chosen voice. Words, letters and phrases missing from it use the device voice in the same gender. */
async function bundled(kind: keyof AudioManifest, key: string): Promise<string | null> {
  const url = (await loadManifest(getVoiceGender()))[kind][key]
  if (url) return url
  // Pure sounds are the one thing device TTS cannot say ("tuh" instead of "t"),
  // so until the male set is generated they keep the female studio clip.
  if (kind === 'sounds' && getVoiceGender() !== 'female') return (await loadManifest('female')).sounds[key] ?? null
  return null
}

async function clipFor(key: string): Promise<string | null> {
  const rec = await getRecordingUrl(key)
  if (rec) return rec
  if (key.startsWith('word:')) return bundled('words', key.slice(5))
  return bundled('sounds', key)
}

setPhraseResolver(async (text) => (await bundled('phrases', text)) ?? bundled('phrases', text.trim()))

/** Say the pure sound of a GPC. */
export function speakSound(gpcId: string, opts: { pauseAfter?: number } = {}): Promise<void> {
  const gpc = GPC_BY_ID[gpcId]
  if (!gpc) return Promise.resolve()
  return enqueue(async () => {
    const clip = await clipFor(gpcId)
    if (clip) await playClip(clip)
    else await speakInline(gpc.speak, gpc.stretchy)
    if (opts.pauseAfter) await new Promise((r) => setTimeout(r, opts.pauseAfter))
  })
}

/** Device voice inside a chain job; pure sounds are stretched a little slower. */
function speakInline(text: string, stretchy: boolean): Promise<void> {
  return speakNow(text, { rate: stretchy ? 0.7 : 0.8 })
}

/** Say the letter's name ("ess"). */
export function speakLetterName(letter: string): Promise<void> {
  const l = letter.toLowerCase()
  return enqueue(async () => {
    const f = await bundled('letters', l)
    if (f) await playClip(f)
    else await speakInline(LETTER_NAMES[l] ?? letter, false)
  })
}

/** Say a whole word naturally. */
export function speakWord(word: string, opts: { rate?: number; pauseAfter?: number } = {}): Promise<void> {
  return enqueue(async () => {
    const clip = await clipFor(`word:${word.toLowerCase()}`)
    if (clip) await playClip(clip)
    else await speakInline(word, false)
    if (opts.pauseAfter) await new Promise((r) => setTimeout(r, opts.pauseAfter))
  })
}

/** Sound out a word: each sound with a short gap, then (optionally) the whole word. */
export async function soundOut(word: DecodableWord, opts: { thenWord?: boolean; gap?: number } = {}): Promise<void> {
  const gap = opts.gap ?? 350
  for (const id of word.gpcs) {
    await speakSound(id)
    await pause(gap)
  }
  if (opts.thenWord) {
    await pause(200)
    await speakWord(word.word)
  }
}

/** Mascot talk: a friendly sentence. */
export function say(text: string, opts: { pauseAfter?: number } = {}): Promise<void> {
  return speak(text, { rate: 0.95, pauseAfter: opts.pauseAfter })
}
